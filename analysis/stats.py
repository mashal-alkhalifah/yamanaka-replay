"""
Small, dependency-free statistics layer.

The repository's reproduction path deliberately depends on numpy and nothing
else, so the handful of inferential tools the analysis needs are implemented
here rather than pulled in from scipy. All of them are resampling- or
closed-form-based and are tested against known values in
``analysis/test_stats.py``.
"""

from __future__ import annotations

import csv
import pathlib

import numpy as np

RESULTS = pathlib.Path(__file__).resolve().parents[1] / "results"


# ------------------------------------------------------------------- loading


def load(filename: str) -> dict[str, np.ndarray]:
    """
    Read a per-run CSV into a dict of columns.

    Numeric columns become float arrays (with empty cells as ``nan``);
    anything else stays as strings. Keeps the analysis free of a dataframe
    dependency while still allowing boolean-mask indexing.
    """
    path = RESULTS / filename
    with path.open(newline="") as fh:
        rows = list(csv.DictReader(fh))
    if not rows:
        raise SystemExit(f"{path} is empty -- run the experiment scripts first")

    columns: dict[str, np.ndarray] = {}
    for key in rows[0]:
        raw = [r.get(key, "") for r in rows]
        try:
            columns[key] = np.array(
                [np.nan if v in ("", "nan") else float(v) for v in raw], dtype=float
            )
        except ValueError:
            columns[key] = np.array(raw, dtype=object)
    return columns


def where(columns: dict[str, np.ndarray], **conditions) -> np.ndarray:
    """Boolean mask selecting rows matching every ``column=value`` condition."""
    mask = np.ones(len(next(iter(columns.values()))), dtype=bool)
    for key, value in conditions.items():
        col = columns[key]
        if col.dtype == object:
            mask &= col == value
        else:
            mask &= np.isclose(col.astype(float), float(value))
    return mask


# ---------------------------------------------------------------- estimation


def bootstrap_ci(
    values: np.ndarray,
    statistic=np.median,
    n_resamples: int = 20_000,
    level: float = 0.95,
    seed: int = 0,
) -> tuple[float, float]:
    """Percentile bootstrap interval for any statistic of one sample."""
    values = np.asarray(values, dtype=float)
    values = values[~np.isnan(values)]
    if values.size == 0:
        return (float("nan"), float("nan"))
    rng = np.random.default_rng(seed)
    idx = rng.integers(0, values.size, size=(n_resamples, values.size))
    draws = statistic(values[idx], axis=1)
    lo, hi = (1 - level) / 2, 1 - (1 - level) / 2
    return float(np.quantile(draws, lo)), float(np.quantile(draws, hi))


def wilson_ci(successes: int, trials: int, z: float = 1.959964) -> tuple[float, float]:
    """
    Wilson score interval for a proportion.

    Preferred over the normal approximation because several conditions here
    produce 0% or 100% success, where the normal interval has zero width and is
    simply wrong.
    """
    if trials == 0:
        return (float("nan"), float("nan"))
    p = successes / trials
    denom = 1 + z**2 / trials
    centre = (p + z**2 / (2 * trials)) / denom
    half = z * np.sqrt(p * (1 - p) / trials + z**2 / (4 * trials**2)) / denom
    return (max(0.0, centre - half), min(1.0, centre + half))


# ------------------------------------------------------------------- testing


def paired_permutation_test(
    a: np.ndarray,
    b: np.ndarray,
    n_resamples: int = 20_000,
    seed: int = 0,
) -> tuple[float, float]:
    """
    Two-sided paired permutation test on the mean difference.

    Under the null, the sign of each pair's difference is exchangeable, so the
    reference distribution is generated by flipping signs at random. Returns
    ``(observed mean difference, p-value)``.

    Used instead of a paired t-test because experiment counts are integer,
    bounded below, and right-skewed.
    """
    a, b = np.asarray(a, dtype=float), np.asarray(b, dtype=float)
    diff = a - b
    diff = diff[~np.isnan(diff)]
    observed = float(diff.mean())
    if diff.size == 0 or np.allclose(diff, 0):
        return observed, 1.0
    rng = np.random.default_rng(seed)
    signs = rng.choice((-1.0, 1.0), size=(n_resamples, diff.size))
    null = (signs * diff).mean(axis=1)
    # +1 in numerator and denominator: the observed value is itself one draw.
    p = (np.sum(np.abs(null) >= abs(observed)) + 1) / (n_resamples + 1)
    return observed, float(min(1.0, p))


def mcnemar_exact(both: int, only_a: int, only_b: int, neither: int) -> float:
    """
    Exact two-sided McNemar test for two paired binary outcomes.

    Only the discordant pairs carry information: under the null they are
    Binomial(n_discordant, 1/2). ``both`` and ``neither`` are accepted for
    readability at the call site and otherwise unused.
    """
    n = only_a + only_b
    if n == 0:
        return 1.0
    k = min(only_a, only_b)
    # Exact binomial tail, computed in log space to stay stable for large n.
    from math import exp, lgamma, log

    def log_choose(n_, k_):
        return lgamma(n_ + 1) - lgamma(k_ + 1) - lgamma(n_ - k_ + 1)

    tail = sum(exp(log_choose(n, i) + n * log(0.5)) for i in range(k + 1))
    return float(min(1.0, 2 * tail))


def logistic_threshold(x: np.ndarray, success: np.ndarray, target: float = 0.5):
    """
    The value of ``x`` at which success probability crosses ``target``.

    Fits a two-parameter logistic in ``log10(x)`` by Newton-Raphson on the
    log-likelihood -- a few lines, and far more informative than reading a
    crossing point off a coarse grid. Returns ``(threshold, slope)``, or
    ``(nan, nan)`` if the data are separable or degenerate.
    """
    x = np.asarray(x, dtype=float)
    y = np.asarray(success, dtype=float)
    keep = x > 0
    x, y = x[keep], y[keep]
    if x.size == 0 or y.min() == y.max():
        return float("nan"), float("nan")

    z = np.log10(x)
    design = np.column_stack([np.ones_like(z), z])
    beta = np.zeros(2)
    for _ in range(200):
        eta = design @ beta
        mu = 1 / (1 + np.exp(-eta))
        w = np.clip(mu * (1 - mu), 1e-9, None)
        hessian = design.T @ (design * w[:, None]) + 1e-8 * np.eye(2)
        step = np.linalg.solve(hessian, design.T @ (y - mu))
        beta += step
        if np.max(np.abs(step)) < 1e-10:
            break
    if abs(beta[1]) < 1e-9:
        return float("nan"), float("nan")
    logit_target = np.log(target / (1 - target))
    return float(10 ** ((logit_target - beta[0]) / beta[1])), float(beta[1])


def loglog_slope(x: np.ndarray, y: np.ndarray) -> float:
    """Least-squares slope of log(y) on log(x): the empirical scaling exponent."""
    x, y = np.asarray(x, dtype=float), np.asarray(y, dtype=float)
    keep = (x > 0) & (y > 0)
    if keep.sum() < 2:
        return float("nan")
    return float(np.polyfit(np.log(x[keep]), np.log(y[keep]), 1)[0])


# ------------------------------------------------------------------ summary


def describe(values: np.ndarray) -> dict[str, float]:
    """Median, mean, IQR, tail percentiles and extremes of one sample."""
    v = np.asarray(values, dtype=float)
    v = v[~np.isnan(v)]
    if v.size == 0:
        return {k: float("nan") for k in ("n", "median", "mean", "q25", "q75", "p90", "p99", "min", "max")}
    return {
        "n": int(v.size),
        "median": float(np.median(v)),
        "mean": float(v.mean()),
        "q25": float(np.percentile(v, 25)),
        "q75": float(np.percentile(v, 75)),
        "p90": float(np.percentile(v, 90)),
        "p99": float(np.percentile(v, 99)),
        "min": float(v.min()),
        "max": float(v.max()),
    }
